"""Package the preserved per-team runtime GLBs and their import metadata."""
import hashlib,json,shutil,struct
from pathlib import Path
root=Path(__file__).resolve().parents[1];assets=root/'assets/f1-2026'
ledger=json.loads((assets/'production.json').read_text());output=root/'vendor/f1-models';output.mkdir(exist_ok=True)
catalog={}
def read_model(model):
 source=assets/model['file'];data=source.read_bytes()
 assert hashlib.sha256(data).hexdigest()==model['sha256'],source
 assert data[:4]==b'glTF' and struct.unpack_from('<I',data,8)[0]==len(data)
 size=struct.unpack_from('<I',data,12)[0]
 return source,data,json.loads(data[20:20+size])
for team in ledger['teams']:
 model=team['runtime_prototype'];source,data,document=read_model(model)
 wheels=[n for n in document['nodes'] if 'wheel' in n.get('extras',{})]
 assert sorted(n['extras']['wheel'] for n in wheels)==list(range(4))
 assert len(document['meshes'])==5 and any(n.get('name')==model['root_name'] for n in document['nodes'])
 assert sum(document['accessors'][p['indices']]['count']//3 for m in document['meshes'] for p in m['primitives'])==model['triangle_count']
 pivots=sorted(model['pivots'],key=lambda p:p['index']);assert [p['index'] for p in pivots]==list(range(4))
 filename=team['id']+'.glb';shutil.copyfile(source,output/filename)
 catalog[team['id']]={'file':filename,'sha256':model['sha256'],'root':model['root_name'],'triangles':model['triangle_count'],
                     'wheels':[{'position':p['pivot_game'],'radius':p['diameter']/2,'width':p['width']} for p in pivots]}
 pov=team.get('pov_runtime_trial')
 if pov:
  profile={key:pov[key] for key in ['eye','look','wheelHub','rakeZ','fov']}
  for kind in ['car','driver']:
   entry=pov[kind];part,encoded,doc=read_model(entry)
   assert len(doc['meshes'])==entry['meshes']
   assert sum(doc['accessors'][p['indices']]['count']//3 for mesh in doc['meshes'] for p in mesh['primitives'])==entry['triangles']
   if kind=='driver':
    assert len(doc['skins'])==4 and sum(len(s['joints']) for s in doc['skins'])==entry['bones']==238
    assert len(doc['animations'])==1 and doc['animations'][0]['name']=='Scene'
   else:assert all(any(n.get('name')==name for n in doc['nodes']) for name in ['body','ferrari_cockpit_lining_trial','ferrari_halo_reference_trial']+['wheel_'+name+'_steer' for name in ['front_left','front_right','rear_left','rear_right']])
   name=team['id']+'-pov-'+kind+'.glb';shutil.copyfile(part,output/name)
   profile[kind]={'file':name,'sha256':entry['sha256'],'triangles':entry['triangles']}
  surfaces=json.loads((assets/pov['surfaces']).read_text())
  assert surfaces['car_sha256']==pov['car']['sha256'] and surfaces['driver_sha256']==pov['driver']['sha256']
  profile['surfaces']={'lcd':{k:surfaces['lcd'][k] for k in ['positions','uvs','indices']},
                       'mirrors':[{k:s[k] for k in ['positions','uvs','indices']} for s in surfaces['mirrors']]}
  catalog[team['id']]['pov']=profile
assert len(catalog)==11
script="// Generated by tools/prepare-f1-package.py from preserved runtime exports.\n(function(root) {\n  const base = new URL('f1-models/', document.currentScript.src);\n  const cars = "+json.dumps(catalog,separators=(',',':'))+";\n  for (const car of Object.values(cars)) {\n    car.url = new URL(car.file, base).href;\n    if (car.pov) for (const part of [car.pov.car, car.pov.driver]) part.url = new URL(part.file, base).href;\n  }\n  root.APEX_TEAM_CARS = cars;\n})(window);\n"
(root/'vendor/f1-cars.js').write_text(script)
print('F1_PACKAGE_READY',len(catalog),'teams;',sum((output/c['file']).stat().st_size for c in catalog.values()),'bytes')
